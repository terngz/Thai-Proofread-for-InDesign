let appVersion = "";
let uiLang = "en";

function tr(key, vars) {
  let s = (I18N[uiLang] && I18N[uiLang][key]);
  if (s === undefined) s = I18N.en[key];
  if (s === undefined) return key;
  const v = vars ? Object.assign({ version: appVersion }, vars) : { version: appVersion };
  s = s.replace(/\{(\w+)\}/g, (m, k) => (v[k] !== undefined ? v[k] : m));
  return s;
}

function applyI18n() {
  const all = document.getElementsByTagName("*");
  for (let i = 0; i < all.length; i++) {
    const n = all[i];
    const k = n.getAttribute && n.getAttribute("data-i18n");
    if (k) n.textContent = tr(k);
    const p = n.getAttribute && n.getAttribute("data-i18n-placeholder");
    if (p) n.setAttribute("placeholder", tr(p));
  }
}

function setUiLang(lang) {
  if (lang !== "th" && lang !== "en") return;
  uiLang = lang;
  applyI18n();
}
